// The generated indexes (rail index/in-sync, advisory): releases/INDEX.md and
// research/INDEX.md are written by `ws index` and are never edited by hand.
// The same functions render them for ws and compare them for the rail.

const NOTE = 'Generated by `node workspace/ws.mjs index`. Do not edit by hand.';

function cell(s) {
  return String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function versionKey(v) {
  return v.split('.').map((n) => n.padStart(6, '0')).join('.');
}

// releases: [{ version, manifest }] (manifest parsed, or null when it does not parse)
export function renderReleasesIndex(releases) {
  const rows = [...releases].sort((a, b) => (versionKey(a.version) < versionKey(b.version) ? 1 : -1)).map(({ version, manifest: m }) => {
    const repos = m && m.repos ? Object.entries(m.repos).filter(([n]) => n !== 'althing').map(([n, r]) => (r.version ? `${n} ${r.version}` : n)).join(', ') : '';
    return `| [${version}](${version}/family.json) | ${cell(m ? m.state : 'unreadable')} | ${cell(m && m.previous)} | ${cell(repos)} |`;
  });
  return ['# Releases', '', NOTE, '', '| Release | State | Previous | Repositories |', '|---|---|---|---|', ...rows, ''].join('\n');
}

function headerField(readme, name) {
  const m = new RegExp(`^\\*\\*${name}:\\*\\*\\s*(.*)$`, 'm').exec(readme || '');
  return m ? m[1].trim() : '';
}

// folders: [{ dir, readme }] (readme text, or '' when missing)
export function renderResearchIndex(folders) {
  const rows = [...folders].sort((a, b) => (a.dir < b.dir ? 1 : -1)).map(({ dir, readme }) => `| [${dir}](${dir}/README.md) | ${cell(headerField(readme, 'Question'))} | ${cell(headerField(readme, 'Status'))} |`);
  return ['# Research', '', NOTE, '', '| Folder | Question | Status |', '|---|---|---|', ...rows, ''].join('\n');
}

export function sameIndex(actual, expected) {
  return actual.replace(/\r\n/g, '\n').trimEnd() === expected.trimEnd();
}
